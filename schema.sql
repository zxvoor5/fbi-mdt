CREATE DATABASE IF NOT EXISTS fbi_mdt CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE fbi_mdt;

CREATE TABLE IF NOT EXISTS agents (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(32) NOT NULL UNIQUE,
  pass_hash VARCHAR(100) NOT NULL,
  role ENUM('admin','agent') NOT NULL DEFAULT 'agent',
  created TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessions (
  token CHAR(64) PRIMARY KEY,
  agent_id INT NOT NULL,
  expires DATETIME NOT NULL,
  FOREIGN KEY (agent_id) REFERENCES agents(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS citizens (
  id VARCHAR(40) PRIMARY KEY, ord INT, name VARCHAR(120), dob VARCHAR(20), phone VARCHAR(40),
  status VARCHAR(20), notes TEXT, records JSON
);
CREATE TABLE IF NOT EXISTS cases (
  id VARCHAR(40) PRIMARY KEY, ord INT, title VARCHAR(200), pri VARCHAR(10), status VARCHAR(10),
  descr TEXT, dt VARCHAR(20)
);
CREATE TABLE IF NOT EXISTS warrants (
  id VARCHAR(40) PRIMARY KEY, ord INT, cid VARCHAR(40), reason TEXT, by_agent VARCHAR(60), dt VARCHAR(20)
);
CREATE TABLE IF NOT EXISTS graph_nodes (
  id VARCHAR(40) PRIMARY KEY, ord INT, name VARCHAR(120), nrole VARCHAR(120), ntype VARCHAR(20),
  status VARCHAR(20), img VARCHAR(500), descr TEXT, subs JSON, x INT, y INT
);
CREATE TABLE IF NOT EXISTS graph_edges (
  id INT AUTO_INCREMENT PRIMARY KEY, a VARCHAR(40), b VARCHAR(40)
);
CREATE TABLE IF NOT EXISTS meta (id INT PRIMARY KEY, version BIGINT NOT NULL);
INSERT INTO meta (id, version) VALUES (1, 0) ON DUPLICATE KEY UPDATE id = id;
